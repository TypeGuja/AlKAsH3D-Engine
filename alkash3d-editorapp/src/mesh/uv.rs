use super::Mesh;
use crate::math::Vec3;

impl Mesh {
    /// ДОБАВЛЕНО (текстуры материалов — по прямому запросу пользователя):
    /// генерирует UV-координаты для каждой вершины планарной проекцией на
    /// одну из трёх осевых плоскостей — выбирается по доминирующей оси уже
    /// сглаженной нормали этой вершины (`self.normals`, должны быть
    /// актуальны — вызывай ПОСЛЕ `recalculate_normals()`), а сами
    /// координаты нормализуются в [0,1] по `self.bounds` (тоже должны быть
    /// актуальны — вызывай ПОСЛЕ `recalculate_bounds()`), так что
    /// назначенное материалу изображение покрывает объект целиком один
    /// раз, а не повторяется мелкой плиткой.
    ///
    /// ОБНОВЛЕНО (честная UV-развёртка примитивов): для плоскогранных
    /// примитивов с общими вершинами между гранями (стык двух граней с
    /// разными доминирующими осями — угол) эта проекция раньше давала
    /// один-единственный UV на вершину, "подходящий" только одной из
    /// граней — визуально развёртка схлопывалась в точку/диагональ (см.
    /// историю git). Для `create_cube()` это исправлено на уровне
    /// топологии — см. её комментарий: у куба теперь каждая грань несёт
    /// СВОИ 4 вершины, ни одна не используется больше чем одной гранью, так
    /// что общей нормали, "усреднённой" сразу под несколько граней, там
    /// больше не возникает.
    ///
    /// ОСТАЮЩЕЕСЯ ОГРАНИЧЕНИЕ: `create_sphere`/`create_cylinder`/
    /// `create_torus` по-прежнему делят вершины между соседними
    /// треугольниками — это НАМЕРЕННО (нужно для гладкого шейдинга
    /// изогнутой поверхности, не то же самое, что жёсткие углы куба), но
    /// значит, что по мере того, как доминирующая ось нормали "переезжает"
    /// с одной оси на другую вдоль изогнутой поверхности (например у
    /// сферы — от полюса к экватору), в этих местах всё ещё возможны
    /// более мягкие UV-швы/растяжение — не схлопывание в точку, как было у
    /// куба, но и не честный unwrap изогнутой поверхности. Полноценная
    /// развёртка для них — самостоятельная задача (настоящая
    /// сферическая/цилиндрическая параметризация вместо доминирующей-оси
    /// планарной проекции), отдельная от этой правки.
    pub fn recalculate_uv(&mut self) {
        let (min, max) = self.bounds;
        let size = Vec3::new(
            (max.x - min.x).max(1e-5),
            (max.y - min.y).max(1e-5),
            (max.z - min.z).max(1e-5),
        );

        self.uv = Vec::with_capacity(self.vertices.len());
        for i in 0..self.vertices.len() {
            let p = self.vertices[i];
            let n = self.normals.get(i).copied().unwrap_or(Vec3::UP);
            let (ax, ay, az) = (n.x.abs(), n.y.abs(), n.z.abs());

            let uv = if ax >= ay && ax >= az {
                // Доминирует X — проецируем на плоскость ZY.
                [(p.z - min.z) / size.z, (p.y - min.y) / size.y]
            } else if ay >= ax && ay >= az {
                // Доминирует Y (верх/низ) — проецируем на плоскость XZ.
                [(p.x - min.x) / size.x, (p.z - min.z) / size.z]
            } else {
                // Доминирует Z — проецируем на плоскость XY.
                [(p.x - min.x) / size.x, (p.y - min.y) / size.y]
            };
            self.uv.push(uv);
        }
    }

    /// ДОБАВЛЕНО (текстуры материалов): подменяет UV, посчитанные
    /// `recalculate_uv()`, на РЕАЛЬНЫЕ координаты из источника геометрии
    /// (например честная развёртка из импортированного `.obj`, см.
    /// `assets/library.rs::parse_obj`) — там, где они есть, они почти
    /// всегда лучше автоматической планарной проекции выше. Молча
    /// игнорирует несовпадающую по длине развёртку (вместо паники/частичной
    /// записи) — оставляет уже посчитанные `recalculate_uv()` координаты,
    /// это безопасный fallback, а не тот случай, из-за которого должна
    /// падать вся загрузка модели.
    pub fn set_uv(&mut self, uv: Vec<[f32; 2]>) {
        if uv.len() == self.vertices.len() {
            self.uv = uv;
        }
    }
}
