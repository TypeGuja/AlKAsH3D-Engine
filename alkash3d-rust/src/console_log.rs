// src/console_log.rs
//! ДОБАВЛЕНО (по просьбе пользователя): сохраняет весь вывод консоли
//! (stdout/stderr — то есть всё, что печатают `println!`/`eprintln!` по
//! всему движку и всем плагинам) одновременно и в реальную консоль, и в
//! .txt-файл на диске, БЕЗ изменения хотя бы одной существующей строчки
//! `println!`/`eprintln!` где-либо ещё в кодовой базе.
//!
//! КАК ЭТО РАБОТАЕТ (стандартный Windows-паттерн "консольный tee"):
//! `println!`/`eprintln!` в Rust на Windows в итоге всегда пишут через
//! хендлы `STD_OUTPUT_HANDLE`/`STD_ERROR_HANDLE` (см. `WriteFile`/
//! `WriteConsoleW` внутри std). Эти хендлы — не что-то, зашитое намертво:
//! их можно подменить через `SetStdHandle` на ЛЮБОЙ другой валидный
//! Windows-хендл, и весь дальнейший вывод любого места программы molча
//! пойдёт туда, включая уже существующий код. Идея: подменяем их на
//! write-конец анонимного pipe (`CreatePipe`), а на другом конце этого
//! pipe в фоновом потоке читаем всё, что туда пишут, и ретранслируем
//! КАЖДЫЙ прочитанный кусок в ДВА места сразу — в оригинальный (настоящий)
//! консольный хендл, который был ДО подмены (поэтому вывод в консоли не
//! пропадает и не меняется), и в открытый .txt-файл лога.
//!
//! Почему не просто "перенаправить stdout в файл" (`SetStdHandle` прямо
//! на хендл файла, без pipe): тогда пропал бы вывод в саму консоль —
//! пользователь видел бы пустое окно, а лог был бы только в файле. Схема
//! с pipe+ретрансляцией сохраняет оба места одновременно.
//!
//! Почему отдельный ПОТОК, а не просто читать/писать синхронно откуда-то:
//! `WriteFile` в pipe с ограниченным буфером БЛОКИРУЕТ пишущего, если
//! никто не вычитывает данные с другого конца — то есть если бы никто не
//! читал pipe, любой `println!` где угодно в движке завис бы намертво,
//! как только буфер pipe заполнился бы. Фоновый поток здесь читает pipe
//! в бесконечном цикле, начиная СРАЗУ после инициализации, поэтому такого
//! зависания не происходит.
//!
//! ИСПРАВЛЕНО (код-ревью: находка про то, что один и тот же поток и читал
//! pipe, и синхронно писал прочитанное в консоль/файл): раньше цикл
//! чтения делал `ReadFile` -> `write_raw` (в консоль) -> `write_all` +
//! `flush` (в файл) -> снова `ReadFile`, ВСЁ в одном потоке. Если запись в
//! файл лога зависала (лог лежит на медленном/заблокированном диске,
//! сетевом пути, или антивирус перехватывает запись), поток переставал
//! читать pipe; pipe (по умолчанию ~4-64KB) заполнялся, и уже ЛЮБОЙ
//! `println!`/`eprintln!` где угодно в движке (главный цикл рендера,
//! физика) блокировался внутри `WriteFile` — то есть зависание всего
//! процесса вообще без участия GPU, неотличимое по симптомам от уже
//! известных GPU-зависаний. Теперь чтение pipe и запись в
//! консоль+файл — два РАЗНЫХ потока, соединённых каналом: поток-читатель
//! только вычитывает pipe и сразу же кладёт прочитанное в канал (быстро,
//! почти никогда не блокируется), а поток-писатель разбирает канал и
//! делает потенциально медленные `write_raw`/`write_all`/`flush` отдельно
//! от чтения pipe. Если запись всё же зависнет, копится очередь в канале
//! (рост памяти), а не блокируется сам pipe — то есть само приложение
//! продолжает работать вместо мгновенной заморозки.

use std::fs::File;
use std::io::{Read, Write};
use std::thread;

use windows::Win32::Foundation::{CloseHandle, HANDLE};
use windows::Win32::System::Console::{
    GetStdHandle, SetStdHandle, STD_ERROR_HANDLE, STD_OUTPUT_HANDLE,
};
use windows::Win32::System::Pipes::CreatePipe;

/// Пишет один и тот же кусок байт в оригинальный консольный хендл и в
/// файл лога. Отдельная функция — используется из фонового потока-ретранслятора.
///
/// ВАЖНО: пишем в оригинальный хендл через сырой `WriteFile`, а не через
/// `std::io::stdout()` — после `SetStdHandle` ниже `std::io::stdout()`
/// сам начинает писать в pipe (это и есть весь смысл подмены), поэтому
/// использование его же здесь привело бы к бесконечной петле "прочитали
/// из pipe -> записали в тот же pipe -> прочитали снова...".
fn write_raw(handle: HANDLE, data: &[u8]) {
    unsafe {
        let mut written: u32 = 0;
        let _ = windows::Win32::Storage::FileSystem::WriteFile(
            handle,
            Some(data),
            Some(&mut written),
            None,
        );
    }
}

/// Заводит один pipe для одного из стандартных потоков (stdout ИЛИ
/// stderr) и запускает фоновый поток-ретранслятор для него.
///
/// `std_handle_id` — `STD_OUTPUT_HANDLE` или `STD_ERROR_HANDLE`.
/// `log_file` — общий (клонированный через `try_clone`) хендл файла лога:
/// stdout и stderr пишут В ОДИН И ТОТ ЖЕ файл, чтобы получился единый
/// хронологический лог, как в реальной консоли, а не два раздельных файла.
fn spawn_tee(std_handle_id: windows::Win32::System::Console::STD_HANDLE, mut log_file: File) -> windows::core::Result<()> {
    unsafe {
        // Оригинальный хендл (настоящая консоль) — сохраняем ДО подмены,
        // именно в него будем дублировать вывод, чтобы пользователь
        // по-прежнему видел всё на экране.
        let original_handle = GetStdHandle(std_handle_id)?;

        let mut read_handle = HANDLE::default();
        let mut write_handle = HANDLE::default();
        CreatePipe(&mut read_handle, &mut write_handle, None, 0)?;

        // С этого момента ВЕСЬ будущий println!/eprintln! (и вообще любая
        // запись в STD_OUTPUT_HANDLE/STD_ERROR_HANDLE где угодно в
        // процессе — включая плагины .dll, если они пишут через
        // унаследованные стандартные хендлы) уходит в pipe вместо
        // реальной консоли напрямую.
        SetStdHandle(std_handle_id, write_handle)?;

        // ИСПРАВЛЕНО (ошибка компиляции: "`*mut c_void` cannot be sent
        // between threads safely"): `HANDLE` — это тонкая обёртка над
        // `*mut c_void` (см. windows-crate), а сырые указатели намеренно
        // НЕ реализуют `Send` — компилятор не может доказать, что их
        // безопасно передавать между потоками (в общем случае указатель
        // может указывать на память, не годную для доступа из другого
        // потока). Здесь это ложное срабатывание: Windows-хендл — просто
        // непрозрачное числовое id уровня ОС, а не указатель на память
        // этого процесса, поэтому передавать его в другой поток совершенно
        // безопасно. Стандартный обход — провезти хендл через поток как
        // обычное число (`isize`, которое `Send` реализует всегда), а
        // внутри потока восстановить `HANDLE` обратно из этого числа.
        let read_handle_raw: isize = read_handle.0 as isize;
        let original_handle_raw: isize = original_handle.0 as isize;

        // Канал между читателем и писателем — см. комментарий выше про то,
        // почему это два потока, а не один. Несвязанный (`channel`, а не
        // `sync_channel`) специально: писатель не должен иметь возможность
        // применить обратное давление на читателя и тем самым снова
        // застопорить вычитывание pipe.
        let (tx, rx) = std::sync::mpsc::channel::<Vec<u8>>();

        // Поток-писатель: разбирает канал и делает потенциально медленные
        // `write_raw`/`write_all`/`flush`. Специально не join'им нигде —
        // должен успеть дописать финальные сообщения (в т.ч.
        // "[MAIN] Goodbye!") даже когда main() уже возвращается; ОС
        // корректно завершает все потоки при выходе из процесса.
        thread::spawn(move || {
            let original_handle = HANDLE(original_handle_raw as *mut core::ffi::c_void);
            while let Ok(chunk) = rx.recv() {
                write_raw(original_handle, &chunk);
                let _ = log_file.write_all(&chunk);
                let _ = log_file.flush();
            }
        });

        // Поток-читатель: живёт всё время работы процесса (до его
        // естественного завершения), только вычитывает pipe и сразу
        // передаёт прочитанное писателю через канал — это быстрая
        // операция, которая почти никогда не блокируется, поэтому
        // медленная запись в файл/консоль (см. поток-писатель выше)
        // больше не может задержать вычитывание pipe и тем самым
        // заблокировать чужой `println!`/`eprintln!` где-либо в движке.
        thread::spawn(move || {
            let read_handle = HANDLE(read_handle_raw as *mut core::ffi::c_void);
            let mut buf = [0u8; 4096];
            loop {
                let mut read: u32 = 0;
                let ok = unsafe {
                    windows::Win32::Storage::FileSystem::ReadFile(
                        read_handle,
                        Some(&mut buf),
                        Some(&mut read),
                        None,
                    )
                };
                if ok.is_err() || read == 0 {
                    // Write-конец закрыт (процесс завершается) — выходим
                    // из потока. `tx` дропнется вместе с этим стеком,
                    // писатель увидит закрытый канал и тоже завершится
                    // сам, дочитав то, что успело накопиться в канале.
                    break;
                }
                let _ = tx.send(buf[..read as usize].to_vec());
            }
            let _ = unsafe { CloseHandle(read_handle) };
        });
    }
    Ok(())
}

/// Точка входа модуля — вызвать ОДИН РАЗ, самым первым делом в `main()`,
/// до первого `println!`. Создаёт (или перезаписывает, если уже
/// существует — каждый запуск начинает лог с нуля) .txt-файл по пути
/// `log_path` и с этого момента дублирует туда весь stdout и stderr
/// процесса, вместе с сохранением обычного вывода в консоль.
///
/// Если что-то в самой настройке пошло не так (например, файл лога
/// невозможно создать — нет прав на запись в директорию) — печатает
/// предупреждение в консоль (используя обычный `eprintln!`, ДО подмены
/// хендлов, так что это сообщение точно попадёт в консоль) и продолжает
/// работу движка БЕЗ логирования в файл, а не паникует и не прерывает
/// запуск — сохранение лога это удобство, а не критичная для работы
/// движка функция.
pub fn init_console_log_to_file(log_path: &str) {
    let file = match File::create(log_path) {
        Ok(f) => f,
        Err(e) => {
            eprintln!(
                "[CONSOLE_LOG] WARNING: не удалось создать файл лога '{}': {} — вывод будет только в консоли",
                log_path, e
            );
            return;
        }
    };
    let file_for_stderr = match file.try_clone() {
        Ok(f) => f,
        Err(e) => {
            eprintln!(
                "[CONSOLE_LOG] WARNING: не удалось клонировать хендл файла лога: {} — вывод будет только в консоли",
                e
            );
            return;
        }
    };

    if let Err(e) = spawn_tee(STD_OUTPUT_HANDLE, file) {
        eprintln!("[CONSOLE_LOG] WARNING: не удалось перенаправить stdout в файл: {:?} — вывод будет только в консоли", e);
        return;
    }
    if let Err(e) = spawn_tee(STD_ERROR_HANDLE, file_for_stderr) {
        eprintln!("[CONSOLE_LOG] WARNING: не удалось перенаправить stderr в файл: {:?}", e);
        return;
    }

    // Это сообщение уже проходит через свежеподменённые хендлы — то есть
    // само попадёт и в консоль (через tee), и в файл лога, служа заодно
    // проверкой, что дублирование реально заработало.
    println!("[CONSOLE_LOG] ✓ Лог консоли сохраняется в файл: {}", log_path);
}
